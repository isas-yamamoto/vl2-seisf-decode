"""
SEISF (DLT) decode path for utig/vkg.1 .. vkg.46.

Background
----------
* DLT labels on UTIG 8-mm cassettes are SEISF: raw lander bit strings with
  spacecraft DRAM address scrambling, as stored at JPL / MIT / Galveston.
* VUS labels (vkg.47-56) are USEIS: the *same* science after N51VUS (PDP-15)
  removed pads, ran MAP/UNSCR, and rewrote frames as 450-byte blocks.

Hardware scramble (PD7400072) + ground inverse (N51SUB):
  The 2048-bit seismometer buffer is read out to the DAPU in an order that
  depends on pointer Q vs 503 (four 512-bit pages; lengths Q+9 and 503-Q).
  N51SUB probes Q via the MAP table (matv) from the first scrambled data pair,
  then SEISDT/UNSCR recomposes sequential buffer bits.

This module:
  1. Walks SEISF cassette structure (1000-byte headers, 10752/10764 records).
  2. Finds 672-byte logical frames (224 halfwords) with SEISF engineering headers.
  3. Exports the 108-byte shared SEISF/VUS header (year, DOY, …).
  4. Unscrambles science via PD7400072 Q-page reordering (with matv/Q scan),
     then hands off to vus_decode for GCSC / mode / amplitudes.

Status (2026-08):
  - Header + PD7400072 Q-page reorder solid.
  - Science Path D (primary): halfword pairs → 36 bits, drop top 4
    (hi[0:4]) keep hi[4:18]||lo[0:18] = 32 bits/pair (BLP-style 32 of 36);
    **Q = matv** (N51SUB NBA/NBB with Q=matv); **bit_offset = 15**.
  - vkg.1↔vkg.47 matched frames: **2048/2048 + full frame equality** with
    next-record halfword lookahead for record-boundary frames.
  - Earlier Q=matv−2 / off=13 left ≤8 page-edge residuals (off-by-two of
    the same pairing). Structural N51SUB BOUT still open as Path E.
  - Frame-header discovery: the header word-1 gate accepts 0o000/0o100/0o200
    (not only 0o100); see _VALID_HI_WORDS. Recovers ~23% more header-matched
    pairs on vkg.1 subgroup 0 (380→423) with no change to bit-exact results.
"""

