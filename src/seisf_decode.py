def _lls(l: int, ac: int, mq: int, n: int) -> Tuple[int, int, int]:
    """LLS matching N51SUB test sheet / materials2 seisf/func.py (AC,MQ,L)."""
    val = ((ac & MASK18) << 19) | ((mq & MASK18) << 1) | (l & 1)
    val = (val << n) & ((1 << 37) - 1)
    l = val & 1
    mq = (val >> 1) & MASK18
    ac = (val >> 19) & MASK18
    return l, ac, mq


def _lrs(l: int, ac: int, mq: int, n: int) -> Tuple[int, int, int]:
    val = (l << 36) | ((ac & MASK18) << 18) | (mq & MASK18)
    val >>= n
    mq = val & MASK18
    ac = (val >> 18) & MASK18
    l = (val >> 36) & 1
    return l, ac, mq


def _ral(l: int, ac: int) -> Tuple[int, int]:
    nl = (ac >> 17) & 1
    ac = ((ac << 1) | (l & 1)) & MASK18
    return nl, ac


def build_map_table() -> list[int]:
    """512-slot MAT[] as generated by N51SUB MAP (values 1..511)."""
    mat = [0] * 512
    temp = 0
    q = -511
    for base_mq in _MAP_BASE:
        mq = base_mq
        for _ in range(18):
            _, temp, mq = _lls(0, temp & 0o777, mq, 1)
            temp &= 0o777
            mat[temp] = q + 512
            q += 1
            if q == 0:
                return mat
    return mat


_MAT = build_map_table()
_ADDR_OF_SEQ = [0] * 512
for _a, _s in enumerate(_MAT):
    if 1 <= _s <= 511:
        _ADDR_OF_SEQ[_s] = _a


